/**
 * Regenerate src/i18n/pages/en.json from src/data/pages.json.
 *
 * This is the translation template: each page has a `texts` array whose
 * length and order must be matched by es.json / fr.json / de.json / zh.json.
 * Read-only with respect to the source data; writes only the template.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractTexts } from '../src/i18n/html.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pages = JSON.parse(
  fs.readFileSync(path.join(root, 'src/data/pages.json'), 'utf8'),
);

const template = {
  _note:
    'Auto-generated by scripts/extract-page-texts.mjs. Translation files must keep the same page keys and texts array lengths.',
  pages: {},
};

let total = 0;
for (const page of pages) {
  const texts = extractTexts(page.html);
  template.pages[page.slug] = { title: page.title, texts };
  total += texts.length;
  console.log(`  ${page.slug.padEnd(20)} ${String(texts.length).padStart(3)} text nodes`);
}

const outFile = path.join(root, 'src/i18n/pages/en.json');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, JSON.stringify(template, null, 2) + '\n', 'utf8');
console.log(`Wrote ${outFile} (${Object.keys(template.pages).length} pages, ${total} text nodes)`);
